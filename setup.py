#!/usr/bin/env python3
"""Nexus AI — Auto-Setup Wizard.

Runs everything automatically:
  1. Checks Python version
  2. Installs dependencies (pip)
  3. Writes .env (prompts for missing values, accepts defaults)
  4. Verifies Telegram bot token via getMe
  5. Sets bot command menu on Telegram (so / shows the command list)
  6. Sets bot description / about text
  7. Creates data directories + SQLite database
  8. Prints next steps

Usage:  python setup.py
"""
import os
import sys
import subprocess
import urllib.request
import json

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(PROJECT_ROOT, ".env")
REQUIREMENTS = os.path.join(PROJECT_ROOT, "requirements.txt")

BOT_COMMANDS = [
    ("start", "🤖 Start / main menu"),
    ("menu", "📋 Open main menu"),
    ("image", "🎨 Generate image from prompt"),
    ("audio", "🔊 Text to speech"),
    ("video", "🎬 Generate video from prompt"),
    ("models", "🧠 List available AI models"),
    ("lang", "🌐 Switch language EN/AR"),
    ("settings", "⚙️ Customize models & defaults"),
    ("clear", "🧹 Clear chat history"),
    ("stats", "📊 Usage statistics (admin)"),
    ("broadcast", "📢 Broadcast message (admin)"),
    ("help", "❓ Show help"),
]

BOT_DESCRIPTION = (
    "Nexus AI — your all-in-one AI assistant in Telegram. "
    "Chat, generate images, audio (TTS), and videos. Type /start to begin."
)
BOT_ABOUT = "✨ Nexus AI | Text · Image · Audio · Video | /start"


def step(msg: str):
    print(f"\n\033[1;36m▶ {msg}\033[0m")


def ok(msg: str):
    print(f"  \033[1;32m✓ {msg}\033[0m")


def warn(msg: str):
    print(f"  \033[1;33m⚠ {msg}\033[0m")


def err(msg: str):
    print(f"  \033[1;31m✗ {msg}\033[0m")


def ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    val = input(f"  {prompt}{suffix}: ").strip()
    return val or default


def tg_api(token: str, method: str, payload: dict) -> dict:
    url = f"https://api.telegram.org/bot{token}/{method}"
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def main():
    print("\033[1;35m" + "=" * 60)
    print("   Nexus AI Bot — Auto Setup Wizard")
    print("=" * 60 + "\033[0m")

    # 1. Python check
    step("Checking Python version…")
    v = sys.version_info
    ok(f"Python {v.major}.{v.minor}.{v.micro}")
    if (v.major, v.minor) < (3, 9):
        err("Python 3.9+ required. Please upgrade.")
        sys.exit(1)

    # 2. Install deps
    step("Installing dependencies…")
    try:
        subprocess.check_call(
            [sys.executable, "-m", "pip", "install", "-q", "-r", REQUIREMENTS],
            stdout=subprocess.DEVNULL,
        )
        ok("Dependencies installed.")
    except subprocess.CalledProcessError as e:
        warn(f"pip install returned {e}; continuing anyway.")

    # 3. Load or create .env
    step("Configuring environment (.env)…")
    env = {}
    if os.path.exists(ENV_PATH):
        for line in open(ENV_PATH, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, val = line.split("=", 1)
                env[k.strip()] = val.strip()
        ok("Existing .env found — values will be kept (press Enter to accept).")
    else:
        ok("No .env found — creating new.")

    token = env.get("TELEGRAM_BOT_TOKEN", "")
    if not token:
        token = ask("Telegram Bot Token (from @BotFather)", "8839749985:AAE3QOPVUPcn1w8kiXXME8bf7SgAdF_7n7Q")
    env["TELEGRAM_BOT_TOKEN"] = token

    admins = env.get("ADMIN_USER_IDS", "")
    if not admins:
        admins = ask("Admin Telegram User IDs (comma-separated, optional)", "")
    env["ADMIN_USER_IDS"] = admins

    allowed = env.get("ALLOWED_USER_IDS", "")
    if not allowed:
        allowed = ask("Restrict to specific user IDs? (comma-separated, leave empty = public)", "")
    env["ALLOWED_USER_IDS"] = allowed

    api_key = env.get("POLLINATIONS_API_KEY", "")
    if not api_key:
        api_key = ask("Pollinations API key (optional, leave empty for anonymous)", "")
    env["POLLINATIONS_API_KEY"] = api_key

    env.setdefault("POLLINATIONS_BASE_URL", "https://gen.pollinations.ai/v1")
    env.setdefault("DEFAULT_LANGUAGE", "en")
    env.setdefault("RATE_LIMIT_SECONDS", "5")
    env.setdefault("MAX_HISTORY_TURNS", "10")
    env.setdefault("DEFAULT_TEXT_MODEL", "gpt-5.4-mini")
    env.setdefault("DEFAULT_IMAGE_MODEL", "turbo")
    env.setdefault("DEFAULT_TTS_VOICE", "Rachel")

    with open(ENV_PATH, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by setup.py\n")
        for k, val in env.items():
            f.write(f"{k}={val}\n")
    ok(f".env written to {ENV_PATH}")

    # 4. Verify token + get bot info
    step("Verifying Telegram bot token…")
    try:
        me = tg_api(token, "getMe", {})
        if me.get("ok"):
            b = me["result"]
            ok(f"Bot verified: @{b.get('username')} ({b.get('first_name')})")
        else:
            err(f"Token invalid: {me.get('description')}")
            sys.exit(1)
    except Exception as e:
        err(f"Cannot reach Telegram API: {e}")
        warn("Continuing — fix network/proxy and re-run setup later.")

    # 5. Set command menu
    step("Setting bot command menu on Telegram…")
    try:
        cmds_payload = [{"command": c, "description": d} for c, d in BOT_COMMANDS]
        r = tg_api(token, "setMyCommands", {"commands": cmds_payload})
        ok("Command menu set." if r.get("ok") else f"setMyCommands: {r}")
    except Exception as e:
        warn(f"Could not set commands: {e}")

    # 6. Set description + about
    try:
        tg_api(token, "setMyDescription", {"description": BOT_DESCRIPTION})
        tg_api(token, "setMyShortDescription", {"short_description": BOT_ABOUT})
        ok("Bot description & about set.")
    except Exception as e:
        warn(f"Could not set description: {e}")

    # 7. Create dirs + DB
    step("Initializing data directories & database…")
    for d in ("data", "data/tmp", "logs"):
        os.makedirs(os.path.join(PROJECT_ROOT, d), exist_ok=True)
    # Trigger DB init
    sys.path.insert(0, PROJECT_ROOT)
    from dotenv import load_dotenv
    load_dotenv(ENV_PATH)
    from bot.database import db  # noqa: F401  — initializes schema
    ok("SQLite database created (data/nexus.db).")

    # 8. Done
    print("\n\033[1;32m" + "=" * 60)
    print("   Setup complete! 🚀")
    print("=" * 60 + "\033[0m")
    print("\nRun the bot with one of these:\n")
    print("  python -m bot.main")
    print("  python bot/main.py")
    if os.name == "nt":
        print("  run.bat   (Windows one-click)")
    print("\nThen open Telegram and send /start to your bot.")
    if admins:
        print(f"\nAdmins ({admins}) get /stats and /broadcast commands.")
    else:
        print("\nTip: add your Telegram User ID to ADMIN_USER_IDS in .env for admin commands.")


if __name__ == "__main__":
    main()
